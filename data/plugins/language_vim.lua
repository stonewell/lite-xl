-- mod-version:4
local syntax = require "core.syntax"

syntax.add {
  name = "VimScript",
  files = { "%.vim$", "%.vimrc$", "%.nvim$", "_vimrc$", "gvimrc$" },
  comment = '"',
  patterns = {
    -- Comments: " at line start or preceded by whitespace, or # in Vim9
    { pattern = '^%s*".*',                              type = "comment" },
    { pattern = '%s+".*',                               type = "comment" },
    { pattern = '^%s*#.*',                              type = "comment" },
    -- Strings
    { pattern = { '"', '"', '\\' },                     type = "string"  },
    { pattern = { "'", "'", '\\' },                     type = "string"  },
    -- Numbers
    { pattern = "0x[%da-fA-F]+",                        type = "number"  },
    { pattern = "-?%d+",                                type = "number"  },
    -- Operators
    { pattern = "[%+%-=/%*%^%%<>!~|&.:]",              type = "operator" },
    -- Option settings
    { pattern = "set()%s+()[%a_][%w_]*",                type = { "keyword", "normal", "keyword2" } },
    { pattern = "setlocal()%s+()[%a_][%w_]*",           type = { "keyword", "normal", "keyword2" } },
    -- Scoped variables: s:var, g:var, b:var, w:var, t:var, v:var, a:var, l:var
    { pattern = "[sgbwtval]:[%a_][%w_]*",               type = "keyword2" },
    -- Function calls
    { pattern = "[%a_][%w_]*%f[(]",                     type = "function" },
    { pattern = "[%a_][%w_]*",                          type = "symbol"   },
  },
  symbols = {
    ["function"]       = "keyword",
    ["endfunction"]    = "keyword",
    ["def"]            = "keyword",
    ["enddef"]         = "keyword",
    ["if"]             = "keyword",
    ["else"]           = "keyword",
    ["elseif"]         = "keyword",
    ["endif"]          = "keyword",
    ["for"]            = "keyword",
    ["in"]             = "keyword",
    ["endfor"]         = "keyword",
    ["while"]          = "keyword",
    ["endwhile"]       = "keyword",
    ["try"]            = "keyword",
    ["catch"]          = "keyword",
    ["finally"]        = "keyword",
    ["endtry"]         = "keyword",
    ["throw"]          = "keyword",
    ["return"]         = "keyword",
    ["let"]            = "keyword",
    ["const"]          = "keyword",
    ["var"]            = "keyword",
    ["unlet"]          = "keyword",
    ["set"]            = "keyword",
    ["setlocal"]       = "keyword",
    ["setglobal"]      = "keyword",
    ["call"]           = "keyword",
    ["echo"]           = "keyword",
    ["echomsg"]        = "keyword",
    ["echoerr"]        = "keyword",
    ["execute"]        = "keyword",
    ["command"]        = "keyword",
    ["autocmd"]        = "keyword",
    ["augroup"]        = "keyword",
    ["syntax"]         = "keyword",
    ["highlight"]      = "keyword",
    ["highlight!"]     = "keyword",
    ["hi"]             = "keyword",
    ["nnoremap"]       = "keyword",
    ["vnoremap"]       = "keyword",
    ["inoremap"]       = "keyword",
    ["xnoremap"]       = "keyword",
    ["cnoremap"]       = "keyword",
    ["noremap"]        = "keyword",
    ["nmap"]           = "keyword",
    ["vmap"]           = "keyword",
    ["imap"]           = "keyword",
    ["map"]            = "keyword",
    ["finish"]         = "keyword",
    ["source"]         = "keyword",
    ["lua"]            = "keyword",
    ["scriptencoding"] = "keyword",
    ["v:true"]         = "literal",
    ["v:false"]        = "literal",
    ["v:null"]         = "literal",
    ["v:none"]         = "literal",
    ["v:count"]        = "literal",
    ["v:version"]      = "literal",
    ["true"]           = "literal",
    ["false"]          = "literal",
    ["null"]           = "literal",
  },
}
